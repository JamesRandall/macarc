import Foundation
import XCTest
@testable import ArchimedesCore

// The Distributed Mandelbrot's guest programs: sources in
// Examples/distributed-mandelbrot, assembled into MandelbrotGuestFiles.swift
// (which the demo network puts on its file server). They're assembled
// again here and must match; MACARCH_WRITE_MANDELBROT=1 writes
// MandelbrotGuestFiles.swift afresh. The worker's compute routine is run
// on an ARM2 and compared with the reference.
final class MandelbrotGuestTests: XCTestCase {
    static let folder = GameSmokeTests.root.appendingPathComponent("Examples/distributed-mandelbrot")
    static let programs: [(source: String, name: String, type: UInt16)] = [("worker", "Worker", 0xFFC), ("mandel", "Mandel", 0xFF8)]

    static func assemble(_ source: String) throws -> ARMAssembler.Assembly {
        try ARMAssembler.assemble(file: folder.appendingPathComponent("\(source).s").path)
    }

    func testBuiltFromTheSources() throws {
        let built = try Self.programs.map { MandelbrotNetwork.GuestFile(name: $0.name, type: $0.type, contents: try Self.assemble($0.source).bytes) }
        if ProcessInfo.processInfo.environment["MACARCH_WRITE_MANDELBROT"] != nil {
            var text = """
            // Generated by MandelbrotGuestTests from Examples/distributed-mandelbrot
            // (MACARCH_WRITE_MANDELBROT=1 swift test --filter MandelbrotGuestTests):
            // the Distributed Mandelbrot's guest programs, as MacArch's assembler
            // assembled them. Don't edit.

            extension MandelbrotNetwork {
                public static let guestFiles: [GuestFile] = [

            """
            for file in built {
                text += "        GuestFile(name: \"\(file.name)\", type: 0x\(String(file.type, radix: 16, uppercase: true)),\n"
                    + "                  base64: \"\(Data(file.contents).base64EncodedString())\"),\n"
            }
            text += "    ]\n}\n"
            let url = GameSmokeTests.root.appendingPathComponent("Packages/ArchimedesCore/Sources/ArchimedesCore/Econet/MandelbrotGuestFiles.swift")
            try text.write(to: url, atomically: true, encoding: .utf8)
            return
        }
        XCTAssertEqual(built.map(\.name), MandelbrotNetwork.guestFiles.map(\.name))
        for (b, embedded) in zip(built, MandelbrotNetwork.guestFiles) {
            XCTAssertEqual(b, embedded, "\(b.name) differs from the sources: MACARCH_WRITE_MANDELBROT=1 swift test --filter MandelbrotGuestTests")
        }
    }

    /// The worker fits the 4K the protocol gives it.
    func testWorkerFitsIn4K() throws {
        XCTAssertLessThanOrEqual(try Self.assemble("worker").bytes.count, 4096)
    }

    /// The worker's own compute routine (shared.s's s_compute, which Mandel
    /// includes too), run on an ARM2 for a few tiles: the counts are the
    /// reference's, byte for byte.
    func testComputeMatchesTheReference() throws {
        let worker = try Self.assemble("worker")
        let entry = try XCTUnwrap(worker.symbols.byName["s_compute"])
        let h = CPUHarness()
        let base: UInt32 = 0x10000, params: UInt32 = 0x20000, out: UInt32 = 0x21000, stack: UInt32 = 0x30000, done: UInt32 = 0x40000
        for (i, b) in worker.bytes.enumerated() { h.bus.mem[Int(base) + i] = b }
        h.bus.put(done, 0xEAFF_FFFE) // B .
        for tile in [0, 19, 107, 130, 151, 175, 229, 299] {
            let assign = MandelbrotMessage.Assign.standard(tile: tile, epoch: 1)
            let fields: [UInt32] = [out, UInt32(bitPattern: assign.startReal), UInt32(bitPattern: assign.startImag),
                                    UInt32(bitPattern: assign.stepReal), UInt32(bitPattern: assign.stepImag),
                                    UInt32(assign.width), UInt32(assign.height), UInt32(assign.maxIterations)]
            for (n, v) in fields.enumerated() { h.bus.put(params + UInt32(n * 4), v) }
            h.cpu.r[0] = params
            h.cpu.r[13] = stack
            h.cpu.r[14] = done
            h.cpu.pc = base + entry
            h.cpu.flushPipeline()
            var steps = 0
            while h.cpu.pc != done + 8 && h.cpu.pc != done + 4 && h.cpu.pc != done && steps < 50_000_000 { h.cpu.step(); steps += 1 }
            let counts = (0 ..< MandelbrotProtocol.tileWidth * MandelbrotProtocol.tileHeight).map { h.bus.mem[Int(out) + $0] }
            XCTAssertEqual(counts, MandelbrotReference.tile(id: tile), "tile \(tile)")
        }
    }
}
